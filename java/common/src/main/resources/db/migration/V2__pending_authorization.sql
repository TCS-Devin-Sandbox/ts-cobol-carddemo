-- IMS DBPAUTP0 (PAUTSUM0 -> PAUTDTL1) and Db2 AUTHFRDS; see docs/schema-mapping-auth.md.

CREATE TABLE pending_auth_summary (
    account_id NUMERIC(11,0) NOT NULL,
    customer_id NUMERIC(9,0) NOT NULL CHECK (customer_id >= 0),
    auth_status CHAR(1) NOT NULL,
    account_status_1 CHAR(2) NOT NULL,
    account_status_2 CHAR(2) NOT NULL,
    account_status_3 CHAR(2) NOT NULL,
    account_status_4 CHAR(2) NOT NULL,
    account_status_5 CHAR(2) NOT NULL,
    credit_limit NUMERIC(11,2) NOT NULL,
    cash_limit NUMERIC(11,2) NOT NULL,
    credit_balance NUMERIC(11,2) NOT NULL,
    cash_balance NUMERIC(11,2) NOT NULL,
    approved_auth_count SMALLINT NOT NULL,
    declined_auth_count SMALLINT NOT NULL,
    approved_auth_amount NUMERIC(11,2) NOT NULL,
    declined_auth_amount NUMERIC(11,2) NOT NULL,
    filler CHAR(34) NOT NULL,
    PRIMARY KEY (account_id)
);

CREATE TABLE pending_auth_detail (
    account_id NUMERIC(11,0) NOT NULL,
    auth_date_inv NUMERIC(5,0) NOT NULL,
    auth_time_inv NUMERIC(9,0) NOT NULL,
    auth_original_date CHAR(6) NOT NULL,
    auth_original_time CHAR(6) NOT NULL,
    card_number CHAR(16) NOT NULL,
    auth_type CHAR(4) NOT NULL,
    card_expiry_date CHAR(4) NOT NULL,
    message_type CHAR(6) NOT NULL,
    message_source CHAR(6) NOT NULL,
    auth_id_code CHAR(6) NOT NULL,
    auth_response_code CHAR(2) NOT NULL,
    auth_response_reason CHAR(4) NOT NULL,
    processing_code NUMERIC(6,0) NOT NULL CHECK (processing_code >= 0),
    transaction_amount NUMERIC(12,2) NOT NULL,
    approved_amount NUMERIC(12,2) NOT NULL,
    merchant_category_code CHAR(4) NOT NULL,
    acquirer_country_code CHAR(3) NOT NULL,
    pos_entry_mode NUMERIC(2,0) NOT NULL CHECK (pos_entry_mode >= 0),
    merchant_id CHAR(15) NOT NULL,
    merchant_name CHAR(22) NOT NULL,
    merchant_city CHAR(13) NOT NULL,
    merchant_state CHAR(2) NOT NULL,
    merchant_zip CHAR(9) NOT NULL,
    transaction_id CHAR(15) NOT NULL,
    match_status CHAR(1) NOT NULL,
    fraud_status CHAR(1) NOT NULL,
    fraud_report_date CHAR(8) NOT NULL,
    filler CHAR(17) NOT NULL,
    PRIMARY KEY (account_id, auth_date_inv, auth_time_inv),
    FOREIGN KEY (account_id) REFERENCES pending_auth_summary (account_id) ON DELETE RESTRICT
);

CREATE TABLE auth_fraud (
    card_number CHAR(16) NOT NULL,
    auth_timestamp TIMESTAMP(6) NOT NULL,
    auth_type CHAR(4),
    card_expiry_date CHAR(4),
    message_type CHAR(6),
    message_source CHAR(6),
    auth_id_code CHAR(6),
    auth_response_code CHAR(2),
    auth_response_reason CHAR(4),
    processing_code CHAR(6),
    transaction_amount NUMERIC(12,2),
    approved_amount NUMERIC(12,2),
    merchant_category_code CHAR(4),
    acquirer_country_code CHAR(3),
    pos_entry_mode SMALLINT,
    merchant_id CHAR(15),
    merchant_name VARCHAR(22),
    merchant_city CHAR(13),
    merchant_state CHAR(2),
    merchant_zip CHAR(9),
    transaction_id CHAR(15),
    match_status CHAR(1),
    fraud_status CHAR(1),
    fraud_report_date DATE,
    account_id NUMERIC(11,0),
    customer_id NUMERIC(9,0),
    PRIMARY KEY (card_number, auth_timestamp)
);

CREATE UNIQUE INDEX auth_fraud_card_ts_desc ON auth_fraud (card_number, auth_timestamp DESC);
